import mongoose from "mongoose";

// One OHLC candle: the open, high, low and close of a stock's price over one time bucket.
//   interval "5m": 5-minute candles, kept 14 CALENDAR days (MongoDB expires them by timestamp and knows nothing of
//                  trading days; 14 calendar days is about 10 trading days, more than the 1D and 1W charts need)
//   interval "1d": one candle per trading day, kept forever
// bucketStart is the exact start instant of the bucket. 5-minute buckets line up with IST because IST's offset of
// 5h30m is a whole number of 5-minute steps; a daily bucket starts at IST midnight.
const candleSchema = new mongoose.Schema({
    stockId: { type: mongoose.Schema.Types.ObjectId, ref: "Stock", required: true },
    interval: { type: String, enum: ["5m", "1d"], required: true },
    bucketStart: { type: Date, required: true },

    open: { type: Number, required: true },
    high: { type: Number, required: true },
    low: { type: Number, required: true },
    close: { type: Number, required: true },

    // true for history generated by the backfill script, false for candles built from live price updates
    synthetic: { type: Boolean, default: false },

    // Only 5-minute candles have it. MongoDB deletes the document when this time passes (TTL index below);
    // documents without the field, like all daily candles, are never expired.
    expireAt: { type: Date }
});

// A bucket exists once per stock and interval. This also makes "create it if missing, otherwise update it" safe
candleSchema.index({ stockId: 1, interval: 1, bucketStart: 1 }, { unique: true });

// Automatic expiry: expireAfterSeconds 0 means "delete at the time stored in expireAt"
candleSchema.index({ expireAt: 1 }, { expireAfterSeconds: 0 });

const Candle = mongoose.model("Candle", candleSchema);

export default Candle;
